use tauri::{AppHandle, Manager, State, command};

use crate::config::{
  ConfigSendChannelState, get_config_from_file, set_config_to_file, stage_config_to_file,
};
use crate::files::{choose_save_destination, file_type_for_extension, pick_file};
use crate::models::config::Config;
use crate::models::log::LogEntry;

#[command]
#[allow(clippy::needless_pass_by_value)]
/// # Errors
/// Returns an error if the main window cannot be found or controlled.
pub fn close_splashscreen(app: AppHandle) -> Result<(), String> {
  let main_window = app
    .get_webview_window("main")
    .ok_or_else(|| "Main window not found".to_string())?;
  main_window.show().map_err(|error| error.to_string())?;

  if let Some(splashscreen) = app.get_webview_window("splashscreen") {
    splashscreen.close().map_err(|error| error.to_string())?;
  }

  Ok(())
}

/// # Errors
/// Returns an error if writing the file fails.
fn write_text_file(path: &std::path::Path, contents: &str) -> Result<(), String> {
  std::fs::write(path, contents).map_err(|error| error.to_string())
}

#[command]
/// Saves text generated by the frontend (log exports, ROV config backups) to
/// a file the user chooses. Returns `false` if they cancelled.
///
/// # Errors
/// Returns an error for an unsupported file type or if the file cannot be
/// written.
pub async fn save_text_file(
  app: AppHandle,
  contents: String,
  title: Option<String>,
  file_name: String,
) -> Result<bool, String> {
  let extension = std::path::Path::new(&file_name)
    .extension()
    .and_then(std::ffi::OsStr::to_str)
    .unwrap_or_default();
  let file_type = file_type_for_extension(extension)?;
  let Some(destination) = choose_save_destination(&app, title, file_name, file_type).await? else {
    return Ok(false);
  };
  write_text_file(destination.path(), &contents)?;
  destination.finish(&app).await
}

#[command]
/// Reads a text file the user picks. Returns `None` if they cancelled.
///
/// # Errors
/// Returns an error for an unsupported file type or an unreadable file.
pub async fn open_text_file(
  app: AppHandle,
  title: Option<String>,
  extension: String,
) -> Result<Option<String>, String> {
  let file_type = file_type_for_extension(&extension)?;
  let Some(path) = pick_file(&app, title, file_type).await? else {
    return Ok(None);
  };
  std::fs::read_to_string(path).map(Some).map_err(|error| error.to_string())
}

#[command]
pub fn get_config() -> Config {
  get_config_from_file()
}

#[command]
pub fn initialize_log_listener() -> Vec<LogEntry> {
  crate::log::initialize_log_listener()
}

#[command]
/// # Errors
/// Returns an error if saving the config file fails or notifying the websocket
/// client task fails.
pub async fn set_config(
  state: State<'_, ConfigSendChannelState>,
  payload: Config,
) -> Result<(), String> {
  set_config_to_file(&state, payload).await
}

#[command]
/// # Errors
/// Returns an error if staging the config file fails.
pub fn stage_config(payload: Config) -> Result<(), String> {
  stage_config_to_file(payload)
}

#[cfg(test)]
mod tests {
  use super::write_text_file;

  /// # Errors
  /// Returns temporary-directory and file IO errors.
  ///
  /// # Panics
  /// Panics if export changes the bytes or leaves old file contents behind.
  #[test]
  fn export_preserves_bytes_and_replaces_existing_contents()
  -> Result<(), Box<dyn std::error::Error>> {
    let directory = tempfile::tempdir()?;
    let path = directory.path().join("logs.jsonl");
    std::fs::write(&path, "old contents that must not remain")?;
    let contents = "{\"message\":\"line one\\nline two λ\"}\n";
    assert_eq!(write_text_file(&path, contents), Ok(()));
    assert_eq!(std::fs::read_to_string(path)?, contents);
    Ok(())
  }

  /// # Errors
  /// Returns temporary-directory creation errors.
  ///
  /// # Panics
  /// Panics if writing to a directory is not reported as an error.
  #[test]
  fn export_reports_write_failure() -> Result<(), Box<dyn std::error::Error>> {
    let directory = tempfile::tempdir()?;
    assert!(write_text_file(directory.path(), "contents").is_err());
    Ok(())
  }
}
